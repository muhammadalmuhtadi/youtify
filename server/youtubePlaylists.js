export function buildSapisidAuthorization(cookieMap, datasyncId = '', useDatasync = true) {
  if (!cookieMap) return '';
  const ts = Math.floor(Date.now() / 1000);
  const parts = [];
  const sapisid = cookieMap.get('SAPISID') || cookieMap.get('__Secure-3PAPISID');
  const sap1p = cookieMap.get('__Secure-1PAPISID');
  const sap3p = cookieMap.get('__Secure-3PAPISID');
  const dsId = String(datasyncId || '').split('||')[0].trim();
  const shouldUseDatasync = Boolean(useDatasync && dsId && !dsId.startsWith('V'));

  const signToken = (label, secret) => {
    if (!secret) return;
    if (shouldUseDatasync) {
      parts.push(`${label} ${ts}_${sha1Hex(`${dsId} ${ts} ${secret} ${YT_ORIGIN}`)}_u`);
    } else {
      parts.push(`${label} ${ts}_${sha1Hex(`${ts} ${secret} ${YT_ORIGIN}`)}`);
    }
  };

  signToken('SAPISIDHASH', sapisid);
  signToken('SAPISID1PHASH', sap1p);
  signToken('SAPISID3PHASH', sap3p);
  return parts.join(' ');
}

/**
 * Issue a YouTube Web InnerTube POST request with full ytcfg / delegated page context when signed in.
 */
async function innerTubePost(endpoint, body, cookieSession = null, refererPath = '/') {
  const cleanPath = endpoint.startsWith('/') ? endpoint : `/${endpoint}`;
  const url = `${YT_ORIGIN}${cleanPath}${cleanPath.includes('?') ? '&' : '?'}prettyPrint=false`;
  const ytCtx = cookieSession?.ytContext || {};
  const clientVersion = ytCtx.clientVersion || INNERTUBE_CLIENT.clientVersion;
  const dsId = ytCtx.datasyncId || '';
  const hasUsableDatasync = Boolean(dsId && !String(dsId).split('||')[0].trim().startsWith('V'));

  const sendAttempt = async (useDatasync) => {
    const headers = {
      'Content-Type': 'application/json',
      Origin: YT_ORIGIN,
      'X-Origin': YT_ORIGIN,
      Referer: `${YT_ORIGIN}${refererPath}`,
      'X-Youtube-Client-Name': '1',
      'X-Youtube-Client-Version': clientVersion,
      'User-Agent': USER_AGENT,
    };

    if (ytCtx.visitorData) {
      headers['X-Goog-Visitor-Id'] = ytCtx.visitorData;
    }

    if (cookieSession?.cookieHeader) {
      headers.Cookie = cookieSession.cookieHeader;
      headers['X-Goog-AuthUser'] = String(ytCtx.sessionIndex ?? '0');
      if (ytCtx.delegatedSessionId) {
        headers['X-Goog-PageId'] = ytCtx.delegatedSessionId;
      }
      const authHeader = buildSapisidAuthorization(cookieSession.cookieMap, dsId, useDatasync);
      if (authHeader) {
        headers.Authorization = authHeader;
      }
    }

    const clientObj = {
      ...INNERTUBE_CLIENT,
      clientVersion,
      ...(ytCtx.visitorData ? { visitorData: ytCtx.visitorData } : {}),
    };

    return fetch(url, {
      method: 'POST',
      headers,
      body: JSON.stringify({
        context: { client: clientObj },
        ...body,
      }),
      signal: AbortSignal.timeout(15000),
    });
  };

  let resp = await sendAttempt(hasUsableDatasync);
  if (
    cookieSession?.cookieHeader &&
    hasUsableDatasync &&
    (resp.status === 401 || resp.status === 403)
  ) {
    resp = await sendAttempt(false);
  }

  let data = null;
  try {
    data = await resp.json();
  } catch {
    // Response was not JSON
  }

  if (!resp.ok) {
    const detail = data?.error?.message || `HTTP ${resp.status}`;
    if (resp.status === 401 || resp.status === 403) {
      throw new Error(
        `YouTube rejected the session credentials (${detail}). Please re-sync your YouTube cookies.`
      );
    }
    throw new Error(`YouTube API error on ${cleanPath}: ${detail}`);
  }

  if (data?.error?.message) {
    throw new Error(`YouTube API error: ${data.error.message}`);
  }
  if (data?.status === 'STATUS_FAILED') {
    throw new Error('YouTube could not complete the playlist change.');
  }

  return data;
}

