function findContinuationToken(node) {
  if (!node || typeof node !== 'object') return null;

  // Prefer continuation tokens attached inside actual item lists first
  const preferredContainers = [];
  const collectPreferred = (cur) => {
    if (!cur || typeof cur !== 'object') return;
    if (
      cur.itemSectionRenderer?.contents ||
      cur.playlistVideoListRenderer?.contents ||
      cur.richGridRenderer?.contents ||
      cur.gridRenderer?.items
    ) {
      const arr =
        cur.itemSectionRenderer?.contents ||
        cur.playlistVideoListRenderer?.contents ||
        cur.richGridRenderer?.contents ||
        cur.gridRenderer?.items;
      if (Array.isArray(arr)) preferredContainers.push(...arr);
    }
    if (Array.isArray(cur.onResponseReceivedActions)) {
      for (const act of cur.onResponseReceivedActions) {
        const appended = act?.appendContinuationItemsAction?.continuationItems;
        if (Array.isArray(appended)) preferredContainers.push(...appended);
      }
    }
    if (Array.isArray(cur)) cur.forEach(collectPreferred);
    else Object.values(cur).forEach(collectPreferred);
  };
  collectPreferred(node);

  const extractTok = (obj) =>
    obj?.continuationItemViewModel?.continuationCommand?.innertubeCommand?.continuationCommand?.token ||
    obj?.continuationItemRenderer?.continuationEndpoint?.continuationCommand?.token ||
    obj?.continuationCommand?.token ||
    null;

  for (const entry of preferredContainers) {
    const tok = extractTok(entry);
    if (tok) return tok;
  }

  let fallbackTok = null;
  const walkAll = (cur) => {
    if (fallbackTok || !cur || typeof cur !== 'object') return;
    const tok = extractTok(cur);
    if (tok) {
      fallbackTok = tok;
      return;
    }
    if (Array.isArray(cur)) cur.forEach(walkAll);
    else Object.values(cur).forEach(walkAll);
  };
  walkAll(node);
  return fallbackTok;
}

function extractPlaylistIdFromLockup(lv) {
  const direct = String(lv?.contentId || '').trim().replace(/^VL/, '');
  if (direct && !/^RD/.test(direct)) return direct;

  let resolved = '';
  const walk = (cur) => {
    if (resolved || !cur || typeof cur !== 'object') return;
    if (cur.browseEndpoint?.browseId) {
      const bid = String(cur.browseEndpoint.browseId).trim().replace(/^VL/, '');
      if (/^(PL|OLAK5uy_|UU|FL|WL|LL|LM)/i.test(bid)) {
        resolved = bid;
        return;
      }
    }
    if (cur.watchEndpoint?.playlistId) {
      const pid = String(cur.watchEndpoint.playlistId).trim();
      if (pid && !/^RD/.test(pid)) {
        resolved = pid;
        return;
      }
    }
    const urlStr = cur.commandMetadata?.webCommandMetadata?.url;
    if (typeof urlStr === 'string' && urlStr.includes('list=')) {
      const m = urlStr.match(/[?&]list=([A-Za-z0-9_-]+)/);
      if (m && !/^RD/.test(m[1])) {
        resolved = m[1];
        return;
      }
    }
    if (Array.isArray(cur)) cur.forEach(walk);
    else Object.values(cur).forEach(walk);
  };
  walk(lv);
  return resolved;
}

export function parsePlaylistCardsFromNode(node, outList, seenIds) {
  if (!node || typeof node !== 'object') return;

  const lv = node.lockupViewModel;
  if (
    lv &&
    (/PLAYLIST/i.test(lv.contentType || '') || Boolean(lv.contentImage?.collectionThumbnailViewModel))
  ) {
    const playlistId = extractPlaylistIdFromLockup(lv);
    if (playlistId && !/^RD/.test(playlistId) && !seenIds.has(playlistId)) {
      seenIds.add(playlistId);
      const title =
        extractText(lv.metadata?.lockupMetadataViewModel?.title).trim() || 'YouTube Playlist';
      const primaryThumb =
        lv.contentImage?.collectionThumbnailViewModel?.primaryThumbnail?.thumbnailViewModel;
      const thumbSources = primaryThumb?.image?.sources || [];
      const cover = thumbSources[thumbSources.length - 1]?.url || '';

      let videoCount = 0;
      const overlays = primaryThumb?.overlays || [];
      for (const ov of overlays) {
        const badges = ov?.thumbnailOverlayBadgeViewModel?.thumbnailBadges || [];
        for (const b of badges) {
          const text = extractText(b?.thumbnailBadgeViewModel?.text);
          const match = text.match(/(\d[\d,.]*)/);
          if (match) {
            videoCount = parseInt(match[1].replace(/[,.]/g, ''), 10) || 0;
            break;
          }
        }
      }

      const subtitleRows =
        lv.metadata?.lockupMetadataViewModel?.metadata?.contentMetadataViewModel?.metadataRows || [];
      const descParts = subtitleRows
        .flatMap((row) => (row.metadataParts || []).map((p) => extractText(p.text).trim()))
        .filter((t) => t && !/^(playlist|view full playlist|private|unlisted|public)$/i.test(t));

      outList.push({
        youtube_playlist_id: playlistId,
        name: title,
        description: descParts.slice(0, 2).join(' • '),
        cover_image: cover,
        video_count: videoCount,
        yt_editable: playlistId === 'LL' ? 0 : 1,
      });
    }
    return;
  }

  const gpr = node.gridPlaylistRenderer || node.playlistRenderer;
  if (gpr?.playlistId && !/^RD/.test(gpr.playlistId) && !seenIds.has(gpr.playlistId)) {
    const playlistId = String(gpr.playlistId).trim();
    seenIds.add(playlistId);
    const thumbArr = gpr.thumbnail?.thumbnails || gpr.thumbnails?.[0]?.thumbnails || [];
    const cover = thumbArr[thumbArr.length - 1]?.url || '';
    const countText = extractText(gpr.videoCountShortText || gpr.videoCountText);
    const videoCount = parseInt(countText.replace(/[^\d]/g, ''), 10) || 0;

    outList.push({
      youtube_playlist_id: playlistId,
      name: extractText(gpr.title).trim() || 'YouTube Playlist',
      description: extractText(gpr.shortBylineText).trim(),
      cover_image: cover,
      video_count: videoCount,
      yt_editable: playlistId === 'LL' ? 0 : 1,
    });
    return;
  }

  if (Array.isArray(node)) {
    for (const item of node) parsePlaylistCardsFromNode(item, outList, seenIds);
  } else {
    for (const val of Object.values(node)) parsePlaylistCardsFromNode(val, outList, seenIds);
  }
}

export function parseAccountIdentityFromMenu(data) {
  let header = null;
  let avatarFallback = '';

  const walk = (cur) => {
    if (!cur || typeof cur !== 'object') return;
    if (cur.activeAccountHeaderRenderer && !header) {
      header = cur.activeAccountHeaderRenderer;
      return;
    }
    if (cur.topbarMenuButtonRenderer?.avatar?.thumbnails?.length && !avatarFallback) {
      const arr = cur.topbarMenuButtonRenderer.avatar.thumbnails;
      avatarFallback = arr[arr.length - 1]?.url || '';
    }
    if (Array.isArray(cur)) cur.forEach(walk);
    else Object.values(cur).forEach(walk);
  };
  walk(data);

  const rawHandle = extractText(header?.channelHandle).trim();
  const handle = rawHandle
    ? rawHandle.startsWith('@')
      ? rawHandle
      : `@${rawHandle}`
    : '';
  const name = extractText(header?.accountName).trim() || (handle ? handle.slice(1) : '');
  const email = extractText(header?.email).trim();
  const photoArr = header?.accountPhoto?.thumbnails || [];
  const avatar_url = photoArr[photoArr.length - 1]?.url || avatarFallback || '';

  return { name, handle, email, avatar_url };
}

