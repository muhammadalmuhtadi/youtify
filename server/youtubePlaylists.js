function findSetVideoIdInNode(node, targetPlaylistId = '') {
  if (!node || typeof node !== 'object') return '';
  if (typeof node.setVideoId === 'string' && node.setVideoId) {
    return node.setVideoId;
  }
  const ep = node.playlistEditEndpoint;
  if (ep && (!targetPlaylistId || ep.playlistId === targetPlaylistId) && Array.isArray(ep.actions)) {
    for (const act of ep.actions) {
      if (act?.setVideoId) return String(act.setVideoId);
    }
  }
  if (Array.isArray(node)) {
    for (const item of node) {
      const found = findSetVideoIdInNode(item, targetPlaylistId);
      if (found) return found;
    }
  } else {
    for (const [key, val] of Object.entries(node)) {
      // Skip the thumbnail hover overlay which targets WL ("Watch Later")
      if (key === 'thumbnailHoverOverlayToggleActionsViewModel') continue;
      const found = findSetVideoIdInNode(val, targetPlaylistId);
      if (found) return found;
    }
  }
  return '';
}

function parseVideosFromNode(node, playlistId, outTracks, seenKeys) {
  if (!node || typeof node !== 'object') return;

  const lv = node.lockupViewModel;
  if (lv && (lv.contentType === 'LOCKUP_CONTENT_TYPE_VIDEO' || (!/PLAYLIST/i.test(lv.contentType || '') && lv.contentId?.length === 11))) {
    const watchEp = lv.rendererContext?.commandContext?.onTap?.innertubeCommand?.watchEndpoint;
    const videoId = String(lv.contentId || watchEp?.videoId || '').trim();
    if (/^[a-zA-Z0-9_-]{11}$/.test(videoId)) {
      const setVideoId = findSetVideoIdInNode(lv.metadata, playlistId);
      const dedupeKey = setVideoId || `${videoId}:${outTracks.length}`;
      const uniqKey = setVideoId ? `sv:${setVideoId}` : `vid:${videoId}`;
      if (!seenKeys.has(uniqKey)) {
        seenKeys.add(uniqKey);
        const meta = lv.metadata?.lockupMetadataViewModel;
        const title = extractText(meta?.title).trim() || `YouTube Video (${videoId})`;
        const rows = meta?.metadata?.contentMetadataViewModel?.metadataRows || [];
        const artist = extractText(rows[0]?.metadataParts?.[0]?.text).trim() || 'YouTube';
        const thumbs = lv.contentImage?.thumbnailViewModel?.image?.sources || [];
        const thumbUrl = thumbs[thumbs.length - 1]?.url || `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;

        let duration = 0;
        const overlays = lv.contentImage?.thumbnailViewModel?.overlays || [];
        for (const ov of overlays) {
          const badges =
            ov?.thumbnailBottomOverlayViewModel?.badges ||
            ov?.thumbnailOverlayBadgeViewModel?.thumbnailBadges ||
            [];
          for (const b of badges) {
            const text = extractText(b?.thumbnailBadgeViewModel?.text);
            const parsedDur = parseDurationToSeconds(text);
            if (parsedDur > 0) {
              duration = parsedDur;
              break;
            }
          }
          if (duration > 0) break;
        }

        outTracks.push({
          youtube_id: videoId,
          yt_set_video_id: setVideoId || '',
          title,
          artist,
          duration,
          thumbnail_url: thumbUrl,
          url: `https://www.youtube.com/watch?v=${videoId}`,
          source_type: 'youtube',
          _dedupe: dedupeKey,
        });
      }
    }
    return;
  }

  const pvr = node.playlistVideoRenderer;
  if (pvr?.videoId && /^[a-zA-Z0-9_-]{11}$/.test(pvr.videoId)) {
    const videoId = String(pvr.videoId).trim();
    const setVideoId = String(pvr.setVideoId || '');
    const uniqKey = setVideoId ? `sv:${setVideoId}` : `vid:${videoId}`;
    if (!seenKeys.has(uniqKey)) {
      seenKeys.add(uniqKey);
      const thumbs = pvr.thumbnail?.thumbnails || [];
      const thumbUrl = thumbs[thumbs.length - 1]?.url || `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg`;
      const duration = Number(pvr.lengthSeconds) > 0
        ? Math.round(Number(pvr.lengthSeconds))
        : parseDurationToSeconds(extractText(pvr.lengthText));

      outTracks.push({
        youtube_id: videoId,
        yt_set_video_id: setVideoId,
        title: extractText(pvr.title).trim() || `YouTube Video (${videoId})`,
        artist: extractText(pvr.shortBylineText).trim() || 'YouTube',
        duration,
        thumbnail_url: thumbUrl,
        url: `https://www.youtube.com/watch?v=${videoId}`,
        source_type: 'youtube',
      });
    }
    return;
  }

  if (Array.isArray(node)) {
    for (const item of node) parseVideosFromNode(item, playlistId, outTracks, seenKeys);
  } else {
    for (const val of Object.values(node)) parseVideosFromNode(val, playlistId, outTracks, seenKeys);
  }
}

function extractPlaylistHeaderMeta(data, fallbackId) {
  const pageHeader = data?.header?.pageHeaderRenderer;
  const pageVm = pageHeader?.content?.pageHeaderViewModel;
  const legacy = data?.header?.playlistHeaderRenderer;

  const title =
    extractText(pageVm?.title?.dynamicTextViewModel?.text).trim() ||
    pageHeader?.pageTitle?.trim() ||
    extractText(legacy?.title).trim() ||
    `YouTube Playlist (${fallbackId})`;

  const description =
    extractText(pageVm?.description?.descriptionPreviewViewModel?.description).trim() ||
    extractText(legacy?.descriptionText).trim() ||
    '';

  const heroSources =
    pageVm?.heroImage?.contentPreviewImageViewModel?.image?.sources ||
    legacy?.playlistHeaderBanner?.heroPlaylistThumbnailRenderer?.thumbnail?.thumbnails ||
    [];
  const cover = heroSources[heroSources.length - 1]?.url || '';
  const editable = Boolean(legacy?.isEditable);

  return { title, description, cover, editable };
}

/**
 * Fetch the signed-in user's /feed/playlists library from initial HTML snapshot + YouTube InnerTube.
 */
export async function fetchUserFeedPlaylists(
  cookieSession,
  initialPlaylistsData = null,
  channelHandle = ''
) {
  if (!cookieSession?.cookieHeader) {
    throw new Error('YouTube browser session cookies are required to load /feed/playlists.');
  }

  const playlists = [];
  const seenIds = new Set();

  const followContinuations = async (initialNode) => {
    let data = initialNode;
    for (let page = 1; page < 5; page++) {
      const token = findContinuationToken(data);
      if (!token) break;
      data = await innerTubePost('/youtubei/v1/browse', { continuation: token }, cookieSession, '/feed/playlists');
      const before = playlists.length;
      parsePlaylistCardsFromNode(data, playlists, seenIds);
      if (playlists.length === before) break;
    }
  };

  if (initialPlaylistsData && typeof initialPlaylistsData === 'object') {
    parsePlaylistCardsFromNode(initialPlaylistsData, playlists, seenIds);
    await followContinuations(initialPlaylistsData).catch(() => {});
  }

  const tryBrowseFeed = async (browseId) => {
    const data = await innerTubePost('/youtubei/v1/browse', { browseId }, cookieSession, '/feed/playlists');
    parsePlaylistCardsFromNode(data, playlists, seenIds);
    await followContinuations(data);
    return data;
  };

  let primaryData = null;
  try {
    primaryData = await tryBrowseFeed('FEplaylist_aggregation');
  } catch {
    // Fallback below if FEplaylist_aggregation rejects rotated PSIDTS cookies
  }
  if (playlists.length === 0) {
    try {
      await tryBrowseFeed('FElibrary');
    } catch {
      // Fallback to channel handle playlists below
    }
  }

  if (playlists.length === 0 && channelHandle) {
    try {
      const cleanHandle = channelHandle.startsWith('@') ? channelHandle : `@${channelHandle}`;
      const nav = await innerTubePost(
        '/youtubei/v1/navigation/resolve_url',
        { url: `${YT_ORIGIN}/${cleanHandle}/playlists` },
        cookieSession,
        `/${cleanHandle}/playlists`
      );
      const ep = nav?.endpoint?.browseEndpoint;
      if (ep?.browseId) {
        const chData = await innerTubePost(
          '/youtubei/v1/browse',
          { browseId: ep.browseId, ...(ep.params ? { params: ep.params } : {}) },
          cookieSession,
          `/${cleanHandle}/playlists`
        );
        parsePlaylistCardsFromNode(chData, playlists, seenIds);
        await followContinuations(chData);
      }
    } catch {
      // Non-fatal channel playlists fallback
    }
  }

  if (playlists.length === 0) {
    throw new Error(
      primaryData && responseLooksLoggedOut(primaryData)
        ? 'YouTube returned a signed-out /feed/playlists view. Please re-connect your YouTube cookies.'
        : 'YouTube returned 0 playlists from /feed/playlists (session token may have rotated).'
    );
  }

  return playlists;
}

/**
 * Fetch all tracks inside a YouTube playlist using 2026 InnerTube, with authenticated HTML ytInitialData fallback.
 */
export async function fetchYouTubePlaylistVideos(youtubePlaylistId, cookieSession = null, maxPages = 5) {
  const cleanId = String(youtubePlaylistId || '').trim().replace(/^VL/, '');
  if (!cleanId) {
    throw new Error('YouTube playlist ID is required.');
  }

  let data = null;
  let meta = { title: '', description: '', cover: '', editable: false };
  const tracks = [];
  const seenKeys = new Set();

  try {
    data = await innerTubePost(
      '/youtubei/v1/browse',
      { browseId: `VL${cleanId}` },
      cookieSession,
      `/playlist?list=${encodeURIComponent(cleanId)}`
    );
    meta = extractPlaylistHeaderMeta(data, cleanId);
    parseVideosFromNode(data, cleanId, tracks, seenKeys);

    for (let page = 1; page < maxPages; page++) {
      const token = findContinuationToken(data);
      if (!token) break;
      data = await innerTubePost(
        '/youtubei/v1/browse',
        { continuation: token },
        cookieSession,
        `/playlist?list=${encodeURIComponent(cleanId)}`
      );
      const before = tracks.length;
      parseVideosFromNode(data, cleanId, tracks, seenKeys);
      if (tracks.length === before) break;
    }
  } catch (err) {
    if (!cookieSession?.cookieHeader) throw err;
  }

  if (tracks.length === 0 && cookieSession?.cookieHeader) {
    try {
      const resp = await fetch(`${YT_ORIGIN}/playlist?list=${encodeURIComponent(cleanId)}`, {
        headers: {
          Cookie: cookieSession.cookieHeader,
          'User-Agent': USER_AGENT,
          'Accept-Language': 'en-US,en;q=0.9',
        },
        signal: AbortSignal.timeout(15000),
      });
      if (resp.ok) {
        const html = await resp.text();
        const htmlData = extractJsonAssignment(html, 'var ytInitialData =');
        if (htmlData) {
          const htmlMeta = extractPlaylistHeaderMeta(htmlData, cleanId);
          meta = {
            title: meta.title || htmlMeta.title,
            description: meta.description || htmlMeta.description,
            cover: meta.cover || htmlMeta.cover,
            editable: meta.editable || htmlMeta.editable,
          };
          parseVideosFromNode(htmlData, cleanId, tracks, seenKeys);
        }
      }
    } catch {
      // Non-fatal fallback attempt
    }
  }

  const normalizedTracks = tracks.map(({ _dedupe, ...rest }) => rest);
  return {
    youtube_playlist_id: cleanId,
    name: meta.title || `YouTube Playlist (${cleanId})`,
    description: meta.description,
    cover_image: meta.cover || normalizedTracks[0]?.thumbnail_url || '',
    yt_editable: meta.editable || Boolean(cookieSession && cleanId !== 'LL'),
    tracks: normalizedTracks,
  };
}

/**
 * Import one public/unlisted YouTube playlist (?list=PL...) or up to 12 playlists from a @handle/channel URL.
 */
export async function fetchPublicYouTubeImport(rawInput) {
  const trimmed = String(rawInput || '').trim();
  if (!trimmed) {
    throw new Error('Enter a YouTube playlist URL, playlist ID, or @channel handle.');
  }

  let listId = null;
  if (/^(PL|OLAK5uy_|UU|FL|RD)[A-Za-z0-9_-]{8,}$/.test(trimmed)) {
    listId = trimmed;
  } else {
    try {
      const normalized = /^https?:\/\//i.test(trimmed)
        ? trimmed
        : trimmed.startsWith('@')
          ? `${YT_ORIGIN}/${trimmed}/playlists`
          : `https://${trimmed}`;
      const parsed = new URL(normalized);
      listId = parsed.searchParams.get('list');
    } catch {
      // Check below as channel handle
    }
  }

  if (listId) {
    const pl = await fetchYouTubePlaylistVideos(listId, null, 5);
    return [pl];
  }

  const targetUrl = trimmed.startsWith('@')
    ? `${YT_ORIGIN}/${trimmed}/playlists`
    : /^https?:\/\//i.test(trimmed)
      ? trimmed.replace(/\/+$/, '') + (trimmed.includes('/playlists') ? '' : '/playlists')
      : `${YT_ORIGIN}/@${trimmed.replace(/^@/, '')}/playlists`;

  const nav = await innerTubePost('/youtubei/v1/navigation/resolve_url', { url: targetUrl });
  const ep = nav?.endpoint?.browseEndpoint;
  if (!ep?.browseId) {
    throw new Error('Could not resolve that YouTube playlist link or channel handle.');
  }

  const browseData = await innerTubePost(
    '/youtubei/v1/browse',
    { browseId: ep.browseId, ...(ep.params ? { params: ep.params } : {}) },
    null,
    '/feed/playlists'
  );

  const cards = [];
  const seen = new Set();
  parsePlaylistCardsFromNode(browseData, cards, seen);
  if (cards.length === 0) {
    throw new Error('No public playlists found on that YouTube channel.');
  }

  const limited = cards.slice(0, 12);
  const fullPlaylists = [];
  for (const card of limited) {
    try {
      const pl = await fetchYouTubePlaylistVideos(card.youtube_playlist_id, null, 3);
      fullPlaylists.push({
        ...pl,
        name: card.name || pl.name,
        description: card.description || pl.description,
        cover_image: card.cover_image || pl.cover_image,
      });
    } catch {
      // Skip private/unavailable sub-playlist
    }
  }
  return fullPlaylists;
}

/**
 * 2-Way Mutation: Create a playlist on the user's YouTube account.
 */
export async function createYouTubePlaylist(
  cookieSession,
  { title, description = '', privacyStatus = 'PRIVATE' }
) {
  const data = await innerTubePost(
    '/youtubei/v1/playlist/create',
    {
      title: String(title || 'Untitled Playlist').trim(),
      privacyStatus,
      videoIds: [],
    },
    cookieSession,
    '/feed/playlists'
  );

  const youtubePlaylistId = data?.playlistId;
  if (!youtubePlaylistId) {
    throw new Error('YouTube did not return a playlistId when creating the playlist.');
  }

  if (description && description.trim()) {
    await innerTubePost(
      '/youtubei/v1/browse/edit_playlist',
      {
        playlistId: youtubePlaylistId,
        actions: [{ action: 'ACTION_SET_PLAYLIST_DESCRIPTION', playlistDescription: description.trim() }],
      },
      cookieSession,
      `/playlist?list=${youtubePlaylistId}`
    ).catch(() => {});
  }

  return { youtubePlaylistId };
}

/**
 * 2-Way Mutation: Rename or update description of a YouTube playlist.
 */
export async function updateYouTubePlaylist(cookieSession, youtubePlaylistId, { title, description }) {
  const cleanId = String(youtubePlaylistId || '').trim();
  if (!cleanId || ['WL', 'LL', 'LM'].includes(cleanId)) return;

  const actions = [];
  if (title !== undefined) {
    actions.push({ action: 'ACTION_SET_PLAYLIST_NAME', playlistName: String(title).trim() });
  }
  if (description !== undefined) {
    actions.push({ action: 'ACTION_SET_PLAYLIST_DESCRIPTION', playlistDescription: String(description).trim() });
  }
  if (actions.length === 0) return;

  await innerTubePost(
    '/youtubei/v1/browse/edit_playlist',
    { playlistId: cleanId, actions },
    cookieSession,
    `/playlist?list=${cleanId}`
  );
}

