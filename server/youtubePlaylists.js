function safeUserFileKey(userId) {
  return String(userId || 'default').replace(/[^a-zA-Z0-9._-]/g, '_');
}

function getSessionFilePath(userId) {
  return path.join(YT_SESSIONS_DIR, `${safeUserFileKey(userId)}.json`);
}

function sha1Hex(value) {
  return crypto.createHash('sha1').update(value, 'utf8').digest('hex');
}

function extractText(node) {
  if (!node) return '';
  if (typeof node === 'string') return node;
  if (typeof node.content === 'string') return node.content;
  if (typeof node.simpleText === 'string') return node.simpleText;
  if (Array.isArray(node.runs)) return node.runs.map((r) => r.text || '').join('');
  return '';
}

function toNetscapeCookiesText(entries) {
  const fallbackExpiry = Math.floor(Date.now() / 1000) + 86400 * 180;
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Younamp YouTube Sync'];

  for (const item of entries) {
    if (!item?.name || item.value === undefined) continue;
    const rawDomain = String(item.domain || '.youtube.com').trim();
    const domain = rawDomain.startsWith('.') ? rawDomain : `.${rawDomain}`;
    const includeSubdomains = 'TRUE';
    const cookiePath = String(item.path || '/').trim() || '/';
    const secure = item.secure ? 'TRUE' : 'FALSE';
    const exp = Number.isFinite(Number(item.expirationDate)) && Number(item.expirationDate) > 0
      ? Math.floor(Number(item.expirationDate))
      : fallbackExpiry;
    const val = String(item.value).replace(/[\r\n\t]/g, '');
    lines.push(`${domain}\t${includeSubdomains}\t${cookiePath}\t${secure}\t${exp}\t${item.name}\t${val}`);
  }

  return `${lines.join('\n')}\n`;
}

/**
 * Parse JSON cookies, Netscape cookies.txt, or a raw DevTools Cookie header.
 */
export function parseYouTubeCookieInput(rawInput) {
  const entries = [];

  if (Array.isArray(rawInput)) {
    for (const item of rawInput) {
      if (!item || typeof item !== 'object') continue;
      const name = String(item.name || '').trim();
      const value = item.value !== undefined && item.value !== null ? String(item.value) : '';
      if (!name || !value) continue;
      entries.push({
        name,
        value,
        domain: item.domain || '.youtube.com',
        path: item.path || '/',
        secure: Boolean(item.secure || name.startsWith('__Secure-') || name.startsWith('__Host-')),
        expirationDate: item.expirationDate,
      });
    }
  } else if (typeof rawInput === 'string') {
    const trimmed = rawInput.trim();
    if (!trimmed) {
      throw new Error('Please provide your YouTube session cookies (Cookie header or cookies.txt).');
    }

    // 1. JSON array or { cookies: [...] }
    if (trimmed.startsWith('[') || trimmed.startsWith('{')) {
      try {
        const parsed = JSON.parse(trimmed);
        const arr = Array.isArray(parsed) ? parsed : Array.isArray(parsed?.cookies) ? parsed.cookies : null;
        if (arr) {
          return parseYouTubeCookieInput(arr);
        }
      } catch {
        // Fall through to text parsers
      }
    }

    // 2. Netscape cookies.txt format (tab-separated 7 columns)
    const lines = trimmed.split(/\r?\n/);
    const looksNetscape =
      trimmed.includes('# Netscape HTTP Cookie File') ||
      lines.some((line) => line.split('\t').length >= 7);

    if (looksNetscape) {
      for (let line of lines) {
        line = line.trim();
        if (!line) continue;
        if (line.startsWith('#HttpOnly_')) {
          line = line.slice('#HttpOnly_'.length);
        } else if (line.startsWith('#')) {
          continue;
        }
        const parts = line.split('\t');
        if (parts.length < 7) continue;
        const [domain, , cookiePath, secureStr, expStr, name, ...rest] = parts;
        const value = rest.join('\t');
        if (!name || !value) continue;
        if (domain && !/youtube\.com|google\.com/i.test(domain)) continue;
        entries.push({
          name: name.trim(),
          value: value.trim(),
          domain: domain.trim() || '.youtube.com',
          path: cookiePath.trim() || '/',
          secure: secureStr.trim().toUpperCase() === 'TRUE',
          expirationDate: Number(expStr) || undefined,
        });
      }
    } else {
      // 3. Raw DevTools HTTP "Cookie: SAPISID=...; SID=..." header string
      const headerBody = trimmed.replace(/^cookie\s*:\s*/i, '');
      const pairs = headerBody.split(';');
      for (const pair of pairs) {
        const eqIdx = pair.indexOf('=');
        if (eqIdx <= 0) continue;
        const name = pair.slice(0, eqIdx).trim();
        const value = pair.slice(eqIdx + 1).trim();
        if (!name || !value) continue;
        entries.push({
          name,
          value,
          domain: '.youtube.com',
          path: '/',
          secure: name.startsWith('__Secure-') || name.startsWith('__Host-') || name.includes('SAPISID'),
        });
      }
    }
  } else {
    throw new Error('Unsupported cookie payload format.');
  }

  const cookieMap = new Map();
  const dedupedEntries = [];
  for (const entry of entries) {
    cookieMap.set(entry.name, entry.value);
  }
  for (const [name, value] of cookieMap.entries()) {
    const sample = entries.findLast((e) => e.name === name) || {};
    dedupedEntries.push({
      name,
      value,
      domain: sample.domain || '.youtube.com',
      path: sample.path || '/',
      secure: Boolean(sample.secure),
      expirationDate: sample.expirationDate,
    });
  }

  const hasAuthCookie = REQUIRED_AUTH_COOKIES.some((k) => cookieMap.has(k));
  if (!hasAuthCookie) {
    throw new Error(
      'No signed-in YouTube auth cookies found (SAPISID or SID missing). Sign in on youtube.com first.'
    );
  }

  const cookieHeader = dedupedEntries.map((e) => `${e.name}=${e.value}`).join('; ');
  const hasSapisid = Boolean(
    cookieMap.get('SAPISID') || cookieMap.get('__Secure-3PAPISID') || cookieMap.get('__Secure-1PAPISID')
  );

  return {
    cookieHeader,
    cookieMap,
    netscapeText: toNetscapeCookiesText(dedupedEntries),
    cookieCount: dedupedEntries.length,
    hasSapisid,
  };
}

/**
 * Extract a balanced JSON object following a JavaScript assignment/call marker in HTML.
 */
export function extractJsonAssignment(html, marker) {
  if (!html || !marker) return null;
  const idx = html.indexOf(marker);
  if (idx === -1) return null;
  const start = html.indexOf('{', idx + marker.length);
  if (start === -1) return null;

  let depth = 0;
  let inString = false;
  let escaped = false;
  for (let i = start; i < html.length; i++) {
    const ch = html[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === '"') inString = false;
    } else {
      if (ch === '"') inString = true;
      else if (ch === '{') depth++;
      else if (ch === '}') {
        depth--;
        if (depth === 0) {
          try {
            return JSON.parse(html.slice(start, i + 1));
          } catch {
            return null;
          }
        }
      }
    }
  }
  return null;
}

/**
 * Extract YouTube ytcfg session context (brand/delegated channel ID, DATASYNC_ID, visitorData).
 */
export function extractYtCfgFromHtml(html) {
  if (!html || typeof html !== 'string') return {};
  const cfg = extractJsonAssignment(html, 'ytcfg.set(') || {};

  const pickStr = (key) => {
    if (typeof cfg[key] === 'string' && cfg[key]) return cfg[key];
    const m = html.match(new RegExp(`"${key}"\\s*:\\s*"([^"]*)"`));
    return m ? m[1] : '';
  };

  let loggedIn = Boolean(cfg.LOGGED_IN);
  if (!cfg.LOGGED_IN) {
    const m = html.match(/"LOGGED_IN"\s*:\s*(true|false)/);
    if (m) loggedIn = m[1] === 'true';
  }

  let sessionIndex =
    cfg.SESSION_INDEX !== undefined && cfg.SESSION_INDEX !== null
      ? String(cfg.SESSION_INDEX)
      : '';
  if (!sessionIndex) {
    const m = html.match(/"SESSION_INDEX"\s*:\s*"?(\d+)"?/);
    sessionIndex = m ? m[1] : '0';
  }

  return {
    loggedIn,
    sessionIndex: sessionIndex || '0',
    delegatedSessionId: pickStr('DELEGATED_SESSION_ID'),
    datasyncId: pickStr('DATASYNC_ID'),
    visitorData: pickStr('VISITOR_DATA'),
    clientVersion: pickStr('INNERTUBE_CLIENT_VERSION') || INNERTUBE_CLIENT.clientVersion,
  };
}

function normalizeYtContext(rawCtx) {
  if (!rawCtx || typeof rawCtx !== 'object') return null;
  return {
    loggedIn: Boolean(rawCtx.loggedIn),
    sessionIndex:
      rawCtx.sessionIndex !== undefined && rawCtx.sessionIndex !== null
        ? String(rawCtx.sessionIndex)
        : '0',
    delegatedSessionId: String(rawCtx.delegatedSessionId || '').trim(),
    datasyncId: String(rawCtx.datasyncId || '').trim(),
    visitorData: String(rawCtx.visitorData || '').trim(),
    clientVersion: String(rawCtx.clientVersion || INNERTUBE_CLIENT.clientVersion).trim(),
  };
}

export function saveUserYouTubeSession(userId, rawInput, ytContext = null) {
  const parsed = parseYouTubeCookieInput(rawInput);
  fs.mkdirSync(YT_SESSIONS_DIR, { recursive: true });
  const updatedAt = new Date().toISOString();
  const normalizedCtx = normalizeYtContext(ytContext);
  const payload = {
    userId,
    updatedAt,
    cookieHeader: parsed.cookieHeader,
    cookieMap: Object.fromEntries(parsed.cookieMap.entries()),
    cookieCount: parsed.cookieCount,
    hasSapisid: parsed.hasSapisid,
    ytContext: normalizedCtx,
  };
  fs.writeFileSync(getSessionFilePath(userId), JSON.stringify(payload, null, 2), 'utf8');
  return {
    connected: true,
    cookieCount: parsed.cookieCount,
    updatedAt,
    hasSapisid: parsed.hasSapisid,
    ytContext: normalizedCtx,
    netscapeText: parsed.netscapeText,
  };
}

export function getUserYouTubeSession(userId) {
  if (!userId) return null;
  try {
    const filePath = getSessionFilePath(userId);
    if (!fs.existsSync(filePath)) return null;
    const raw = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    if (!raw?.cookieHeader || !raw?.cookieMap) return null;
    return {
      userId: raw.userId || userId,
      updatedAt: raw.updatedAt || '',
      cookieHeader: raw.cookieHeader,
      cookieMap: new Map(Object.entries(raw.cookieMap)),
      cookieCount: Number(raw.cookieCount || Object.keys(raw.cookieMap).length),
      hasSapisid: Boolean(raw.hasSapisid),
      ytContext: normalizeYtContext(raw.ytContext),
    };
  } catch {
    return null;
  }
}

export function clearUserYouTubeSession(userId) {
  if (!userId) return false;
  try {
    const filePath = getSessionFilePath(userId);
    if (fs.existsSync(filePath)) {
      fs.unlinkSync(filePath);
    }
    return true;
  } catch {
    return false;
  }
}

export function getUserYouTubeSessionStatus(userId) {
  const session = getUserYouTubeSession(userId);
  return {
    connected: Boolean(session),
    updatedAt: session?.updatedAt || '',
    cookieCount: session?.cookieCount || 0,
    hasSapisid: Boolean(session?.hasSapisid),
  };
}

