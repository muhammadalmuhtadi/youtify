/**
 * 2-Way Mutation: Add a YouTube video to a playlist and return its setVideoId.
 */
export async function addVideoToYouTubePlaylist(cookieSession, youtubePlaylistId, videoId) {
  const cleanId = String(youtubePlaylistId || '').trim();
  const cleanVideoId = String(videoId || '').trim();
  if (!cleanId || !cleanVideoId) return { setVideoId: '' };

  const data = await innerTubePost(
    '/youtubei/v1/browse/edit_playlist',
    {
      playlistId: cleanId,
      actions: [{ action: 'ACTION_ADD_VIDEO', addedVideoId: cleanVideoId }],
    },
    cookieSession,
    `/playlist?list=${cleanId}`
  );

  const setVideoId =
    data?.playlistEditResults?.[0]?.playlistEditVideoAddedResultData?.setVideoId ||
    findSetVideoIdInNode(data, cleanId) ||
    '';
  return { setVideoId };
}

/**
 * 2-Way Mutation: Remove a video from a YouTube playlist using setVideoId or fallback videoId.
 */
export async function removeVideoFromYouTubePlaylist(
  cookieSession,
  youtubePlaylistId,
  { videoId, setVideoId }
) {
  const cleanId = String(youtubePlaylistId || '').trim();
  if (!cleanId || cleanId === 'LL') return;

  if (setVideoId) {
    try {
      await innerTubePost(
        '/youtubei/v1/browse/edit_playlist',
        {
          playlistId: cleanId,
          actions: [
            {
              action: 'ACTION_REMOVE_VIDEO',
              setVideoId,
              ...(videoId ? { removedVideoId: videoId } : {}),
            },
          ],
        },
        cookieSession,
        `/playlist?list=${cleanId}`
      );
      return;
    } catch {
      // Fallback below by videoId if setVideoId became stale
    }
  }

  if (videoId) {
    await innerTubePost(
      '/youtubei/v1/browse/edit_playlist',
      {
        playlistId: cleanId,
        actions: [{ action: 'ACTION_REMOVE_VIDEO_BY_VIDEO_ID', removedVideoId: videoId }],
      },
      cookieSession,
      `/playlist?list=${cleanId}`
    );
  }
}

/**
 * 2-Way Mutation: Reorder a track inside a YouTube playlist after predecessorSetVideoId (or top when null).
 */
export async function reorderVideoInYouTubePlaylist(
  cookieSession,
  youtubePlaylistId,
  { setVideoId, predecessorSetVideoId = null }
) {
  const cleanId = String(youtubePlaylistId || '').trim();
  if (!cleanId || !setVideoId || cleanId === 'LL') return;

  const action = {
    action: 'ACTION_MOVE_VIDEO_AFTER',
    setVideoId,
  };
  if (predecessorSetVideoId) {
    action.movedSetVideoIdPredecessor = predecessorSetVideoId;
  }

  await innerTubePost(
    '/youtubei/v1/browse/edit_playlist',
    {
      playlistId: cleanId,
      actions: [action],
    },
    cookieSession,
    `/playlist?list=${cleanId}`
  );
}
